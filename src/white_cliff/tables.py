"""HTML table cells, used when the filing has no XBRL fact for that line."""

from __future__ import annotations

import re
from decimal import Decimal
from html.parser import HTMLParser

from white_cliff.facts import Fact, Period, SourcePointer
from white_cliff.ids import letter_id
from white_cliff.prices import is_price_text

_LABEL_ROLES: tuple[tuple[str, str], ...] = (
    ("total net sales", "revenue"),
    ("total revenue", "revenue"),
    ("total revenues", "revenue"),
    ("net sales", "revenue"),
    ("revenues", "revenue"),
    ("revenue", "revenue"),
    ("gross profit", "gross_profit"),
    ("operating income", "operating_income"),
    ("net income", "net_income"),
    ("cash and cash equivalents", "cash"),
    ("long term debt", "debt"),
    ("operating cash flow", "operating_cash_flow"),
    ("cash generated by operating activities", "operating_cash_flow"),
    ("net cash provided by operating activities", "operating_cash_flow"),
    ("shares outstanding", "shares"),
)

_SECTION = {
    "revenue": "Income statement",
    "gross_profit": "Income statement",
    "operating_income": "Income statement",
    "net_income": "Income statement",
    "operating_cash_flow": "Cash flows",
    "debt": "Balance sheet",
    "cash": "Balance sheet",
    "shares": "Equity",
}

_TABLE_NAME = {
    "income": "Income statement",
    "balance": "Balance sheet",
    "cashflow": "Cash flows",
    "other": "Statements",
}


class _Tables(HTMLParser):
    def __init__(self) -> None:
        super().__init__(convert_charrefs=True)
        self.tables: list[list[list[str]]] = []
        self._depth = 0
        self._rows: list[list[str]] = []
        self._row: list[str] = []
        self._cell: list[str] = []
        self._capture = False

    def handle_starttag(self, tag: str, attrs) -> None:
        tag = tag.lower()
        if tag == "table":
            if self._depth == 0:
                self._rows = []
            self._depth += 1
        elif tag == "tr" and self._depth:
            self._row = []
        elif tag in {"td", "th"} and self._depth:
            self._cell = []
            self._capture = True

    def handle_endtag(self, tag: str) -> None:
        tag = tag.lower()
        if tag in {"td", "th"} and self._capture:
            text = re.sub(r"\s+", " ", "".join(self._cell)).strip()
            self._row.append(text)
            self._capture = False
        elif tag == "tr" and self._depth:
            if any(cell.strip() for cell in self._row):
                self._rows.append(self._row)
        elif tag == "table" and self._depth:
            self._depth -= 1
            if self._depth == 0:
                self.tables.append(self._rows)

    def handle_data(self, data: str) -> None:
        if self._capture:
            self._cell.append(data)


def _norm_label(label: str) -> str:
    cleaned = label.lower()
    cleaned = re.sub(r"\(\d+\)", " ", cleaned)
    cleaned = re.sub(r"[^a-z\s]", " ", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip()


def _role_for(label: str) -> str:
    if "per share" in label:
        return ""
    for key, role in _LABEL_ROLES:
        if label == key:
            return role
    return ""


def _parse_number(text: str) -> Decimal | None:
    cleaned = text.replace("\xa0", "").replace(",", "").replace("$", "").strip()
    if cleaned.startswith("(") and cleaned.endswith(")"):
        cleaned = "-" + cleaned[1:-1]
    cleaned = cleaned.rstrip("%").strip()
    if re.fullmatch(r"-?\d+(?:\.\d+)?", cleaned):
        return Decimal(cleaned)
    return None


def _comma_form(value: Decimal) -> str:
    sign = "-" if value < 0 else ""
    whole, _, fraction = format(abs(value), "f").partition(".")
    grouped = f"{int(whole):,}"
    if fraction and set(fraction) != {"0"}:
        return sign + grouped + "." + fraction.rstrip("0")
    return sign + grouped


def _locate(raw: str, label: str, value: Decimal, offset: int) -> tuple[int, int] | None:
    plain = format(abs(value), "f")
    if "." in plain:
        plain = plain.rstrip("0").rstrip(".")
    comma = _comma_form(abs(value))
    anchor = raw.find(label, offset) if label else -1
    start_at = anchor if anchor >= 0 else offset
    for token in (comma, plain):
        found = raw.find(token, start_at)
        if found >= 0:
            return found, found + len(token)
    return None


def _table_kind(rows: list[list[str]]) -> str:
    blob = " ".join(cell for row in rows for cell in row).lower()
    if "operating activities" in blob or "cash flows" in blob:
        return "cashflow"
    if "total assets" in blob or blob.startswith("assets") or "\nassets" in blob or "assets:" in blob:
        return "balance"
    if "net sales" in blob or "operating income" in blob or "revenue" in blob:
        return "income"
    return "other"


def _span_hint(kind: str, rows: list[list[str]]) -> str:
    blob = " ".join(cell for row in rows[:3] for cell in row).lower()
    if kind == "balance":
        return "period end"
    if "three months" in blob:
        return "quarter"
    if "twelve months" in blob or "year ended" in blob:
        return "fiscal year"
    return "reported period"


def _unit_for(role: str, document_text: str) -> str:
    lowered = document_text.lower()
    share_row = role == "shares"
    millions = "in millions" in lowered
    thousands = "in thousands" in lowered
    shares_in_thousands = "shares, which are reflected in thousands" in lowered
    if share_row and (shares_in_thousands or thousands):
        return "shares thousands"
    if share_row:
        return "shares"
    if millions:
        return "USD millions"
    if thousands and not millions:
        return "USD thousands"
    return "USD"


def parse_tables(text: str, document: str, url: str, sha256: str) -> tuple[list[Fact], bool]:
    parser = _Tables()
    parser.feed(text)
    facts: list[Fact] = []
    price_metric = False
    offset = 0
    for rows in parser.tables:
        kind = _table_kind(rows)
        span = _span_hint(kind, rows)
        for row in rows:
            if not row:
                continue
            label = ""
            for cell in row:
                if cell.strip() and cell.strip() not in {"$", "—", "-"} and _parse_number(cell) is None:
                    label = cell.strip()
                    break
            if not label:
                continue
            if is_price_text(label):
                price_metric = True
                continue
            normalized = _norm_label(label)
            role = _role_for(normalized)
            if not role:
                continue
            value = None
            for cell in row:
                parsed = _parse_number(cell)
                if parsed is not None:
                    value = parsed
                    break
            if value is None:
                continue
            located = _locate(text, label, value, offset)
            if located is None:
                continue
            start, end = located
            offset = end
            unit = _unit_for(role, text)
            period_kind = "instant" if kind == "balance" or role in {"cash", "debt"} else "duration"
            period = Period(kind=period_kind, key=f"{kind}-current")
            fact_id = letter_id(
                "fact",
                f"{document}|{normalized}|{value}|{start}|{role}",
            )
            facts.append(
                Fact(
                    id=fact_id,
                    concept=label,
                    label=label,
                    value=value,
                    unit=unit,
                    period=period,
                    source=SourcePointer(
                        document=document,
                        section=_SECTION[role],
                        url=url,
                        sha256=sha256,
                        table=_TABLE_NAME[kind],
                        row=label,
                        column="current",
                        char_start=start,
                        char_end=end,
                    ),
                    role=role,
                    origin="table",
                    kind="shares" if role == "shares" else "amount",
                    table_kind=kind,
                    span_hint=span if period_kind == "duration" else "period end",
                )
            )
    return facts, price_metric
