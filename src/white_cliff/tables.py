"""HTML table cells, used when the filing has no XBRL fact for that line."""

from __future__ import annotations

import re
from dataclasses import dataclass
from decimal import Decimal
from html.parser import HTMLParser

from white_cliff.facts import Fact, Period, SourcePointer
from white_cliff.ids import letter_id
from white_cliff.prices import is_price_text

_LABEL_ROLES: tuple[tuple[str, str], ...] = (
    ("total net sales", "revenue"),
    ("total revenue", "revenue"),
    ("total revenues", "revenue"),
    ("net sales", "revenue"),
    ("revenues", "revenue"),
    ("revenue", "revenue"),
    ("gross profit", "gross_profit"),
    ("operating income", "operating_income"),
    ("net income", "net_income"),
    ("cash and cash equivalents", "cash"),
    ("long term debt", "debt"),
    ("operating cash flow", "operating_cash_flow"),
    ("cash generated by operating activities", "operating_cash_flow"),
    ("net cash provided by operating activities", "operating_cash_flow"),
    ("shares outstanding", "shares"),
)

_SECTION = {
    "revenue": "Income statement",
    "gross_profit": "Income statement",
    "operating_income": "Income statement",
    "net_income": "Income statement",
    "operating_cash_flow": "Cash flows",
    "debt": "Balance sheet",
    "cash": "Balance sheet",
    "shares": "Equity",
}

_TABLE_NAME = {
    "income": "Income statement",
    "balance": "Balance sheet",
    "cashflow": "Cash flows",
    "other": "Statements",
}

_MONTHS = {
    "january": 1,
    "february": 2,
    "march": 3,
    "april": 4,
    "may": 5,
    "june": 6,
    "july": 7,
    "august": 8,
    "september": 9,
    "october": 10,
    "november": 11,
    "december": 12,
}

_SCALE_WORD = re.compile(r"\b(thousands|millions|billions)\b", re.I)
_SCALE_CAPTION = re.compile(
    r"\([^)]{0,200}?in\s+(?:billions|millions|thousands)\b[^)]{0,200}\)",
    re.I,
)
_DATE = re.compile(
    r"(January|February|March|April|May|June|July|August|September|"
    r"October|November|December)\s+(\d{1,2}),?\s*(\d{4})",
    re.I,
)
_YEAR = re.compile(r"\b(?:19|20)\d{2}\b")
_SPAN_RANK = {"": 3, "fiscal year": 2, "year to date": 1, "quarter": 0}


@dataclass
class _Cell:
    text: str
    colspan: int
    start: int = 0
    end: int = 0


class _Tables(HTMLParser):
    def __init__(self, raw: str) -> None:
        super().__init__(convert_charrefs=True)
        self.tables: list[tuple[str, str, list[list[_Cell]]]] = []
        self._raw = raw
        self._line_starts = [0]
        for index, char in enumerate(raw):
            if char == "\n":
                self._line_starts.append(index + 1)
        self._depth = 0
        self._rows: list[list[_Cell]] = []
        self._row: list[_Cell] = []
        self._cell: list[str] = []
        self._colspan = 1
        self._cell_start = 0
        self._capture = False
        self._in_caption = False
        self._caption: list[str] = []
        self._outside: list[str] = []
        self._lead_scale = ""
        self._table_lead = ""

    def _abs(self) -> int:
        line, offset = self.getpos()
        if line <= 0:
            return 0
        base = self._line_starts[min(line - 1, len(self._line_starts) - 1)]
        return min(base + offset, len(self._raw))

    def handle_starttag(self, tag: str, attrs) -> None:
        tag = tag.lower()
        values = {key.lower(): value for key, value in attrs}
        if tag == "table":
            if self._depth == 0:
                self._finish_outside()
                self._rows = []
                self._caption = []
                self._table_lead = self._lead_scale
            self._depth += 1
        elif tag == "caption" and self._depth:
            self._in_caption = True
            self._caption = []
        elif tag == "tr" and self._depth:
            self._row = []
        elif tag in {"td", "th"} and self._depth:
            self._cell = []
            self._capture = True
            self._cell_start = self._abs()
            try:
                self._colspan = max(int(values.get("colspan") or "1"), 1)
            except ValueError:
                self._colspan = 1

    def handle_endtag(self, tag: str) -> None:
        tag = tag.lower()
        if tag == "caption":
            self._in_caption = False
        elif tag in {"td", "th"} and self._capture:
            text = re.sub(r"\s+", " ", "".join(self._cell)).strip()
            self._row.append(_Cell(text, self._colspan, self._cell_start, self._abs()))
            self._capture = False
        elif tag == "tr" and self._depth:
            if any(cell.text.strip() for cell in self._row):
                self._rows.append(self._row)
        elif tag == "table" and self._depth:
            self._depth -= 1
            if self._depth == 0:
                caption = re.sub(r"\s+", " ", "".join(self._caption)).strip()
                self.tables.append((caption, self._table_lead, self._rows))
                self._table_lead = ""
        elif self._depth == 0:
            self._finish_outside()

    def _finish_outside(self) -> None:
        text = re.sub(r"\s+", " ", "".join(self._outside)).strip()
        self._outside = []
        if not text:
            return
        if _SCALE_CAPTION.fullmatch(text):
            self._lead_scale = text
        else:
            self._lead_scale = ""

    def handle_data(self, data: str) -> None:
        if self._capture or self._in_caption:
            target = self._cell if self._capture else self._caption
            target.append(data)
        elif self._depth == 0:
            self._outside.append(data)


def _norm_label(label: str) -> str:
    cleaned = label.lower()
    cleaned = re.sub(r"\(\d+\)", " ", cleaned)
    cleaned = re.sub(r"[^a-z\s]", " ", cleaned)
    return re.sub(r"\s+", " ", cleaned).strip()


def _role_for(label: str) -> str:
    if "per share" in label:
        return ""
    for key, role in _LABEL_ROLES:
        if label == key:
            return role
    return ""


def _plain_number(text: str) -> Decimal | None:
    """A value cell. Percents, footnotes, and omissions are not values."""
    cleaned = text.replace("\xa0", "").replace(",", "").replace("$", "").strip()
    if not cleaned or cleaned in {"—", "-", "–", "$"}:
        return None
    lowered = cleaned.lower()
    if "[" in cleaned or "*" in cleaned or "redacted" in lowered or "omitted" in lowered:
        return None
    if cleaned.endswith("%"):
        return None
    if re.fullmatch(r"\(\d\)", cleaned):
        return None
    if cleaned.startswith("(") and cleaned.endswith(")"):
        inner = cleaned[1:-1].strip()
        if re.fullmatch(r"\d+(?:\.\d+)?", inner):
            return Decimal("-" + inner)
        return None
    if re.fullmatch(r"-?\d+(?:\.\d+)?", cleaned):
        return Decimal(cleaned)
    return None


def _merge_parens(cells: list[_Cell]) -> list[_Cell]:
    merged: list[_Cell] = []
    index = 0
    while index < len(cells):
        text = cells[index].text.strip()
        span = cells[index].colspan
        start = cells[index].start
        end = cells[index].end
        if (
            text.startswith("(")
            and not text.endswith(")")
            and index + 1 < len(cells)
            and cells[index + 1].text.strip() in {")", " )"}
        ):
            text = text + ")"
            span += cells[index + 1].colspan
            end = cells[index + 1].end
            index += 2
        else:
            index += 1
        merged.append(_Cell(text, max(span, 1), start, end))
    return merged


def _place(cells: list[_Cell]) -> list[tuple[int, str, int, int, int]]:
    placed: list[tuple[int, str, int, int, int]] = []
    pos = 0
    for cell in _merge_parens(cells):
        placed.append((pos, cell.text, cell.colspan, cell.start, cell.end))
        pos += cell.colspan
    return placed


def _full_end(text: str) -> str:
    match = _DATE.search(text)
    if not match:
        return ""
    month = _MONTHS[match.group(1).lower()]
    return f"{int(match.group(3)):04d}-{month:02d}-{int(match.group(2)):02d}"


def _year_key(text: str) -> str:
    full = _full_end(text)
    if full:
        return full[:4]
    years = _YEAR.findall(text)
    return years[-1] if years else ""


def _span_name(text: str) -> str:
    lowered = text.lower()
    if "three months" in lowered or "three month" in lowered:
        return "quarter"
    if (
        "six months" in lowered
        or "nine months" in lowered
        or "year to date" in lowered
        or "year-to-date" in lowered
    ):
        return "year to date"
    if "twelve months" in lowered or "year ended" in lowered or "fiscal year" in lowered:
        return "fiscal year"
    return ""


def _header_columns(rows: list[list[_Cell]]) -> list[dict[str, object]]:
    span_ranges: list[tuple[int, int, str]] = []
    dates: list[tuple[int, int, str, str]] = []
    for row in rows:
        placed = _place(row)
        texts = [text for _pos, text, _span, _start, _end in placed]
        if any(_role_for(_norm_label(text)) for text in texts):
            continue
        for pos, text, colspan, _start, _end in placed:
            named = _span_name(text)
            if named:
                span_ranges.append((pos, pos + colspan, named))
            end = _full_end(text)
            year = _year_key(text)
            if end or year:
                dates.append((pos, colspan, end, year))
    columns: list[dict[str, object]] = []
    for pos, colspan, end, year in dates:
        named = ""
        for start, stop, span in span_ranges:
            if start <= pos < stop:
                named = span
        columns.append({"pos": pos, "width": colspan, "end": end, "year": year, "span": named})
    return columns


def _column_order(column: dict[str, object]) -> tuple[str, str]:
    return (str(column.get("year") or ""), str(column.get("end") or ""))


def _current_column(columns: list[dict[str, object]]) -> dict[str, object] | None:
    if not columns:
        return None
    latest = max(_column_order(column) for column in columns)
    current = [column for column in columns if _column_order(column) == latest]
    current.sort(key=lambda column: (_SPAN_RANK.get(str(column["span"]), 3), int(column["pos"])))
    return current[0]


def _chunks_in(placed: list[tuple[int, str, int, int, int]], start: int, width: int) -> list[str]:
    stop = start + width
    found: list[str] = []
    for pos, text, colspan, _start, _end in placed:
        if pos >= stop or pos + colspan <= start:
            continue
        if text.strip():
            found.append(text.strip())
    return found


def _value_in_column(placed: list[tuple[int, str, int, int, int]], column: dict[str, object]) -> Decimal | None:
    chunks = _chunks_in(placed, int(column["pos"]), int(column["width"]))
    joined: list[str] = []
    index = 0
    while index < len(chunks):
        text = chunks[index]
        if text.startswith("(") and not text.endswith(")") and index + 1 < len(chunks) and chunks[index + 1] == ")":
            joined.append(text + ")")
            index += 2
        else:
            joined.append(text)
            index += 1
    number = None
    for text in joined:
        parsed = _plain_number(text)
        if parsed is not None:
            number = parsed
            break
        if text not in {"$", "—", "-", "–"} and _plain_number(text) is None and text.strip():
            # A non-value such as a percent, footnote, or omission blocks the column.
            if text.endswith("%") or text.startswith("[") or text.startswith("(") or "*" in text:
                return None
    return number


def _has_scale(text: str) -> bool:
    return _SCALE_WORD.search(text) is not None


def _dollar_unit(scale_text: str) -> str | None:
    """One scale word, including "dollars in X" or "amounts in X" when X is that word."""
    words = {match.group(1).lower() for match in _SCALE_WORD.finditer(scale_text)}
    if len(words) != 1:
        return None
    return f"USD {next(iter(words))}"


def _table_kind(rows: list[list[_Cell]]) -> str:
    blob = " ".join(cell.text for row in rows for cell in row).lower()
    if "operating activities" in blob or "cash flows" in blob:
        return "cashflow"
    if "total assets" in blob or "assets:" in blob:
        return "balance"
    if "net sales" in blob or "operating income" in blob or "revenue" in blob:
        return "income"
    return "other"


def _comma_form(value: Decimal) -> str:
    sign = "-" if value < 0 else ""
    whole, _, fraction = format(abs(value), "f").partition(".")
    grouped = f"{int(whole):,}"
    if fraction and set(fraction) != {"0"}:
        return sign + grouped + "." + fraction.rstrip("0")
    return sign + grouped


def _column_bounds(
    placed: list[tuple[int, str, int, int, int]],
    column: dict[str, object],
) -> tuple[int, int] | None:
    start = int(column["pos"])
    stop = start + int(column["width"])
    found_start: int | None = None
    found_end: int | None = None
    for pos, text, colspan, cell_start, cell_end in placed:
        if pos >= stop or pos + colspan <= start:
            continue
        if _plain_number(text) is None:
            continue
        if cell_end <= cell_start:
            continue
        found_start = cell_start if found_start is None else min(found_start, cell_start)
        found_end = cell_end if found_end is None else max(found_end, cell_end)
    if found_start is None or found_end is None:
        return None
    return found_start, found_end


_COMMENT = re.compile(r"<!--.*?-->", re.S)


def _visible_ranges(raw: str, start: int, end: int) -> list[tuple[int, int]]:
    ranges: list[tuple[int, int]] = []
    pos = start
    for comment in _COMMENT.finditer(raw, start, end):
        if comment.start() > pos:
            ranges.append((pos, comment.start()))
        pos = max(pos, comment.end())
    if pos < end:
        ranges.append((pos, end))
    return ranges


def _locate_in(raw: str, start: int, end: int, value: Decimal) -> tuple[int, int] | None:
    plain = format(abs(value), "f")
    if "." in plain:
        plain = plain.rstrip("0").rstrip(".")
    comma = _comma_form(abs(value))
    tokens = sorted({comma, plain}, key=len, reverse=True)
    for piece_start, piece_end in _visible_ranges(raw, start, end):
        window = raw[piece_start:piece_end]
        for token in tokens:
            if not token:
                continue
            match = re.search(rf"(?<![\d,]){re.escape(token)}(?!\d)", window)
            if match:
                return piece_start + match.start(), piece_start + match.end()
    return None


def parse_tables(text: str, document: str, url: str, sha256: str) -> tuple[list[Fact], bool]:
    parser = _Tables(text)
    parser.feed(text)
    facts: list[Fact] = []
    price_metric = False
    for caption, lead, rows in parser.tables:
        kind = _table_kind(rows)
        columns = _header_columns(rows)
        chosen = _current_column(columns)
        header_text = " ".join(cell.text for row in rows[:4] for cell in row)
        scale_text = f"{caption} {header_text}"
        if not _has_scale(scale_text) and _SCALE_CAPTION.fullmatch(lead.strip()):
            scale_text = f"{lead} {scale_text}"
        for row in rows:
            placed = _place(row)
            label = ""
            for _pos, cell, _span, _start, _end in placed:
                if cell.strip() and _role_for(_norm_label(cell)):
                    label = cell.strip()
                    break
            if not label:
                continue
            if is_price_text(label):
                price_metric = True
                continue
            normalized = _norm_label(label)
            role = _role_for(normalized)
            if not role or role == "shares":
                continue
            if chosen is None:
                numbers = []
                for pos, cell, colspan, _start, _end in placed:
                    parsed = _plain_number(cell)
                    if parsed is not None:
                        numbers.append((pos, parsed, colspan))
                if len(numbers) != 1:
                    continue
                pos, value, colspan = numbers[0]
                chosen_here = {"pos": pos, "width": colspan, "end": "", "year": "", "span": ""}
                value = _value_in_column(placed, chosen_here)
            else:
                value = _value_in_column(placed, chosen)
            if value is None:
                continue
            unit = _dollar_unit(scale_text)
            if unit is None:
                continue
            column = chosen if chosen is not None else chosen_here
            bounds = _column_bounds(placed, column)
            if bounds is None:
                continue
            located = _locate_in(text, bounds[0], bounds[1], value)
            if located is None:
                continue
            start, end = located
            column = chosen if chosen is not None else chosen_here
            end_date = str(column["end"])
            span = str(column["span"])
            instant = kind == "balance" or role in {"cash", "debt"}
            if instant:
                span = "period end"
            period = Period(
                kind="instant" if instant else "duration",
                end=end_date,
                span=span,
                key=f"{span}|{end_date}",
            )
            fact_id = letter_id(
                "fact",
                f"{document}|{normalized}|{value}|{start}|{role}",
            )
            facts.append(
                Fact(
                    id=fact_id,
                    concept=label,
                    label=label,
                    value=value,
                    unit=unit,
                    period=period,
                    source=SourcePointer(
                        document=document,
                        section=_SECTION[role],
                        url=url,
                        sha256=sha256,
                        table=_TABLE_NAME[kind],
                        row=label,
                        column="current",
                        char_start=start,
                        char_end=end,
                    ),
                    role=role,
                    origin="table",
                    kind="shares" if role == "shares" else "amount",
                    table_kind=kind,
                    span_hint=span if not instant else "period end",
                )
            )
    return facts, price_metric
